package config

import "context"

// Uninstaller 由**调用方**实现「怎么卸载自己」。
//
// 它与 Upgrader / Restarter / Relistener 并列，是**相互独立**的扩展点：
// 只升级不重启、只重启不卸载、只卸载不重启，都是真实存在的部署。
// 因此它单独注入（见 WithUninstaller），不从 Restarter 上断言出来 ——
// 强绑的话「只想暴露卸载」的部署会被迫连「重启」按钮一起露出来。
//
// 未注入时 /fs/uninstall 返回 404，界面上也不显示「卸载」按钮 ——
// 免得给一个点了必然失败的按钮。
//
// 库自己**不删任何东西**。卸载是比升级（换掉自己的二进制）更不可逆的操作：
// 删二进制、注销 systemd 单元、清配置目录、通知编排器 …… 各家不同，
// 与其它扩展点同一个理由：怎么做由部署方按自己的威胁模型决定。
type Uninstaller interface {
	// Uninstall 执行卸载。返回 nil 表示「已经安排好了」—— 进程可能马上就退。
	//
	// 与 Restart 同样的契约：这个 HTTP 响应是尽力而为。实现方若删掉自己的
	// 二进制再退出，客户端多半只看到连接中断 —— 前端必须把「连接断开」当成
	// 卸载的正常表现，随后靠轮询 /fs/health **没**回来确认它确实停了。
	//
	// ctx 由服务端带上，已经脱开请求上下文（浏览器一关连接就会取消
	// r.Context()，而卸载可能要好一会儿），并带 5 分钟超时。
	Uninstall(ctx context.Context) error
}
